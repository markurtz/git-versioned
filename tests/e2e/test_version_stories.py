def polyglot(repo: RepoBuilder) -> None:
    """Commit a project with Python, Rust, npm, Helm, Docker and citation files."""
    repo.commit(
        "feat: add the project",
        {
            "pyproject.toml": PYPROJECT,
            "src/acme/__init__.py": "from .version import __version__\n",
            ".gitignore": "src/acme/version.py\ndist/\n",
            "Cargo.toml": CARGO,
            "Cargo.lock": CARGO_LOCK,
            "packages/web/package.json": PACKAGE_JSON,
            "deploy/Chart.yaml": CHART,
            "CITATION.cff": CITATION,
            "Dockerfile": DOCKERFILE,
        },
    )


class TestS1BuildVersion:
    """S1: the right version in every build with no config."""

    @pytest.mark.smoke
    def test_release_tag(self, repo: RepoBuilder) -> None:
        """A clean tagged HEAD is that release."""
        repo.tag("v1.2.0")
        assert repo.run("version").first == "1.2.0"

    @pytest.mark.regression
    def test_annotated_tag(self, repo: RepoBuilder) -> None:
        """An annotated tag at HEAD is a release, not a dev build."""
        repo.tag("v1.2.0", annotated=True)
        assert repo.run("version").first == "1.2.0"

    @pytest.mark.regression
    @pytest.mark.parametrize("tag", ["v1.3.0-rc.1", "v1.3.0rc1"])
    def test_pre_release_tag(self, repo: RepoBuilder, tag: str) -> None:
        """Both pre-release tag spellings give the release candidate."""
        repo.tag("v1.2.0")
        repo.commit("feat: next")
        repo.tag(tag)
        assert repo.run("version").first == "1.3.0rc1"
        assert repo.run("version", "--standard", "semver").first == "1.3.0-rc.1"

    @pytest.mark.sanity
    def test_dev_after_tag(self, repo: RepoBuilder) -> None:
        """Commits after a tag give a dev build of the next patch."""
        repo.tag("v1.2.0")
        sha = repo.commit("feat: next")
        result = repo.run("version")
        assert re.fullmatch(rf"1\.2\.1\.dev\d{{8}}\+{sha[:7]}", result.first)

    @pytest.mark.regression
    def test_dev_after_rc_stays_on_release(self, repo: RepoBuilder) -> None:
        """Commits after an rc are dev builds of the release the rc belongs to."""
        repo.tag("v1.2.0-rc.1")
        repo.commit("fix: more")
        assert repo.run("version").first.startswith("1.2.0.dev")

    @pytest.mark.sanity
    def test_highest_tag_on_commit_wins(self, repo: RepoBuilder) -> None:
        """A final and its rc on one commit resolve to the final."""
        repo.tag("v1.2.0-rc.1")
        repo.tag("v1.2.0")
        assert repo.run("version").first == "1.2.0"

    @pytest.mark.sanity
    def test_pin(self, repo: RepoBuilder) -> None:
        """A pinned version skips git, from the argument or the environment."""
        assert repo.run("version", "2.0.0").first == "2.0.0"
        assert (
            repo.run("version", env={"GITVERSIONED__VERSION": "3.0.0rc1"}).first
            == "3.0.0rc1"
        )

    @pytest.mark.regression
    def test_hatchling_build(self, repo: RepoBuilder) -> None:
        """A real wheel build carries the tag version and the generated module."""
        polyglot(repo)
        repo.tag("v1.2.0")
        subprocess.run(
            [
                sys.executable,
                "-m",
                "build",
                "--wheel",
                "--no-isolation",
                "--outdir",
                "dist",
            ],
            cwd=repo.path,
            check=True,
            capture_output=True,
        )
        wheels = list((repo.path / "dist").glob("*.whl"))
        assert [wheel.name.split("-")[1] for wheel in wheels] == ["1.2.0"]
        with zipfile.ZipFile(wheels[0]) as archive:
            module = archive.read("acme/version.py").decode()
        assert '__version__ = version = "1.2.0"' in module
        assert repo.run("version").first == "1.2.0"


class TestS2NoSilentWrongVersion:
    """S2: shallow clones, missing git and tarballs never give a silent wrong version."""

    @pytest.mark.smoke
    def test_shallow_clone_fails_in_ci(self, repo: RepoBuilder, tmp_path: Path) -> None:
        """A shallow clone without tags exits 3 in CI and names the fix."""
        repo.tag("v1.2.0")
        repo.commit("feat: a")
        repo.commit("feat: b")
        clone = tmp_path / "shallow"
        subprocess.run(
            ["git", "clone", "-q", "--depth", "1", f"file://{repo.path}", str(clone)],
            check=True,
        )
        shallow = RepoBuilder.__new__(RepoBuilder)
        shallow.path = clone
        result = shallow.run("version", env={"CI": "true"})
        assert result.code == 3
        assert "fetch-depth: 0" in result.err
        local = shallow.run("version")
        assert local.code == 0
        assert local.first.startswith("0.1.0.dev")
        check = shallow.run("check", env={"CI": "true"})
        assert check.code == 3
        assert "shallow clone" in check.err

    @pytest.mark.regression
    def test_git_archive_tarball(self, repo: RepoBuilder, tmp_path: Path) -> None:
        """A git archive of a tagged commit keeps its version without git."""
        assert repo.run("init").code == 0
        repo.commit("build: add archive file")
        repo.tag("v1.4.0")
        data = subprocess.run(
            ["git", "archive", "--format=tar", "v1.4.0"],
            cwd=repo.path,
            check=True,
            capture_output=True,
        ).stdout
        target = tmp_path / "unpacked"
        with tarfile.open(fileobj=io.BytesIO(data)) as archive:
            archive.extractall(target, filter="data")
        unpacked = RepoBuilder.__new__(RepoBuilder)
        unpacked.path = target
        result = unpacked.run("version", env={"CI": "true"})
        assert (result.code, result.first) == (0, "1.4.0")

    @pytest.mark.sanity
    def test_archive_after_tag(self, tmp_path: Path) -> None:
        """An archive of a commit past the tag is a dev build with the distance."""
        folder = tmp_path / "plain"
        folder.mkdir()
        (folder / ".git_archival.txt").write_text(
            "node: 0123456789abcdef0123456789abcdef01234567\n"
            "node-date: 2026-11-25T10:00:00+00:00\n"
            "describe-name: v1.4.0-3-g0123456\n"
            "ref-names: HEAD -> main\n",
            encoding="utf-8",
        )
        plain = RepoBuilder.__new__(RepoBuilder)
        plain.path = folder
        assert (
            plain.run("version", "--standard", "pep440").first
            == "1.4.1.dev20261125+0123456789a"
        )

    @pytest.mark.sanity
    def test_sdist_metadata(self, tmp_path: Path) -> None:
        """An unpacked sdist uses the version recorded in PKG-INFO."""
        folder = tmp_path / "sdist"
        folder.mkdir()
        (folder / "PKG-INFO").write_text(
            "Metadata-Version: 2.1\nName: acme\nVersion: 1.2.0\n", encoding="utf-8"
        )
        plain = RepoBuilder.__new__(RepoBuilder)
        plain.path = folder
        assert plain.run("version", env={"CI": "true"}).first == "1.2.0"

    @pytest.mark.sanity
    def test_no_source_at_all(self, tmp_path: Path) -> None:
        """With nothing to read, CI fails and a local run warns and falls back."""
        folder = tmp_path / "empty"
        folder.mkdir()
        plain = RepoBuilder.__new__(RepoBuilder)
        plain.path = folder
        assert plain.run("version", env={"CI": "true"}).code == 3
        local = plain.run("version", "--standard", "pep440")
        assert local.code == 0
        assert local.first.startswith("0.1.0.dev")


class TestS3PublishableVersions:
    """S3: dev and nightly builds that registries accept."""

    @pytest.mark.smoke
    def test_nightly_has_no_local_part(self, repo: RepoBuilder) -> None:
        """A nightly is a dev release of the next version with no local part."""
        repo.tag("v1.2.0")
        repo.commit("feat: next")
        assert re.fullmatch(
            r"1\.3\.0\.dev\d{8}", repo.run("version", "--type", "nightly").first
        )
        semver = repo.run("version", "--type", "nightly", "--standard", "semver").first
        assert re.fullmatch(r"1\.3\.0-nightly\.\d{8}", semver)

    @pytest.mark.sanity
    def test_local_can_be_turned_off(self, repo: RepoBuilder) -> None:
        """Dev builds drop the hash when local is false."""
        repo.tag("v1.2.0")
        repo.commit("fix: next")
        result = repo.run("version", env={"GITVERSIONED__LOCAL": "false"})
        assert re.fullmatch(r"1\.2\.1\.dev\d{8}", result.first)

    @pytest.mark.sanity
    def test_dev_and_nightly_base_are_configurable(self, repo: RepoBuilder) -> None:
        """The dev and nightly keys choose the base of each build type."""
        repo.tag("v1.2.0")
        repo.commit("fix: next")
        assert repo.run("version", env={"GITVERSIONED__DEV": "minor"}).first.startswith(
            "1.3.0.dev"
        )
        assert repo.run("version", env={"GITVERSIONED__DEV": "next"}).first.startswith(
            "1.2.1.dev"
        )
        nightly = repo.run(
            "version", "--type", "nightly", env={"GITVERSIONED__NIGHTLY": "major"}
        )
        assert nightly.first.startswith("2.0.0.dev")

    @pytest.mark.regression
    def test_commit_date_is_reproducible(self, repo: RepoBuilder) -> None:
        """The dev number is the commit date, so a rebuild gives the same version."""
        repo.tag("v1.2.0")
        repo.commit("fix: next")
        stamp = repo.git("log", "-1", "--format=%cd", "--date=format:%Y%m%d")
        assert f".dev{stamp}" in repo.run("version").first


class TestS4BuildKeepsTreeClean:
    """S4: stamping does not make the tree dirty."""

    @pytest.mark.smoke
    def test_stamped_manifests_do_not_count(self, repo: RepoBuilder) -> None:
        """After --write on a release tag the version is still the release."""
        polyglot(repo)
        repo.tag("v1.2.0")
        assert repo.run("version", "--write").code == 0
        assert repo.git("status", "--porcelain", "--untracked-files=no") != ""
        assert repo.run("version").first == "1.2.0"

    @pytest.mark.regression
    def test_real_edit_counts(self, repo: RepoBuilder) -> None:
        """A change beyond the version in a manifest makes the tree dirty."""
        polyglot(repo)
        repo.tag("v1.2.0")
        repo.write("Cargo.toml", CARGO.replace('edition = "2021"', 'edition = "2024"'))
        assert repo.run("version").first.endswith(".dirty")


class TestS5OneVersionEverywhere:
    """S5: one version across Python, Rust, npm, Helm, Docker and citation files."""

    @pytest.mark.smoke
    def test_stamp_all(self, repo: RepoBuilder) -> None:
        """Each target gets the version in its own spelling, and nothing else moves."""
        polyglot(repo)
        repo.tag("v1.3.0-rc.1")
        result = repo.run("version", "--write")
        assert result.code == 0
        cargo = repo.read("Cargo.toml")
        assert cargo == (
            CARGO.replace(
                'version = "0.0.0"\nedition', 'version = "1.3.0-rc.1"\nedition'
            )
            .replace(
                'path = "crates/util", version = "0.0.0"',
                'path = "crates/util", version = "1.3.0-rc.1"',
            )
            .replace('version = "=0.0.0"', 'version = "=1.3.0-rc.1"')
        )
        assert 'serde = { version = "1.0" }' in cargo
        assert repo.read("Cargo.lock") == CARGO_LOCK.replace(
            'name = "acme-core"\nversion = "0.0.0"',
            'name = "acme-core"\nversion = "1.3.0-rc.1"',
        )
        assert repo.read("packages/web/package.json") == PACKAGE_JSON.replace(
            "0.0.0", "1.3.0-rc.1"
        )
        assert repo.read("deploy/Chart.yaml") == CHART.replace("0.0.0", "1.3.0-rc.1")
        assert "version: 1.3.0-rc.1\n" in repo.read("CITATION.cff")
        assert "date-released: 2020-01-01" not in repo.read("CITATION.cff")
        assert repo.read("Dockerfile") == DOCKERFILE.replace("0.0.0", "1.3.0-rc.1")
        assert '__version__ = version = "1.3.0rc1"' in repo.read("src/acme/version.py")

    @pytest.mark.sanity
    def test_dry_run_changes_nothing(self, repo: RepoBuilder) -> None:
        """--dry-run prints diffs and leaves the files alone."""
        polyglot(repo)
        result = repo.run("version", "2.0.0", "--write", "--dry-run")
        assert '+version = "2.0.0"' in result.out
        assert repo.read("Cargo.toml") == CARGO
        assert not (repo.path / "src/acme/version.py").exists()

    @pytest.mark.sanity
    def test_listed_targets(self, repo: RepoBuilder) -> None:
        """A key target and a pattern target are stamped beside discovered ones."""
        repo.commit(
            "feat: add files",
            {
                "gitversioned.toml": (
                    '[[targets]]\npath = "pnpm-workspace.yaml"\nkey = "catalog.acme-core"\n\n'
                    "[[targets]]\npath = \"docs/install.md\"\npattern = 'acme==(?P<version>[^\\s`]+)'\n\n"
                    '[[targets]]\npath = "meta.toml"\nkey = "tool.demo.version"\n'
                ),
                "pnpm-workspace.yaml": "packages:\n  - packages/*\ncatalog:\n  react: ^18.0.0\n  acme-core: 0.0.0\n",
                "docs/install.md": "Run `pip install acme==0.0.0` to install.\n",
                "meta.toml": '[tool.demo]\nversion = "0.0.0"\n',
            },
        )
        assert repo.run("version", "1.5.0", "--write").code == 0
        assert "  acme-core: 1.5.0\n" in repo.read("pnpm-workspace.yaml")
        assert "react: ^18.0.0" in repo.read("pnpm-workspace.yaml")
        assert "acme==1.5.0`" in repo.read("docs/install.md")
        assert 'version = "1.5.0"' in repo.read("meta.toml")

    @pytest.mark.regression
    def test_crlf_and_trailing_bytes_survive(self, repo: RepoBuilder) -> None:
        """Line endings and a missing final newline are preserved."""
        raw = b'{\r\n  "name": "x",\r\n  "version": "0.0.0"\r\n}'
        (repo.path / "package.json").write_bytes(raw)
        repo.git("add", "-A")
        repo.commit("feat: npm")
        repo.run("version", "1.0.0", "--write")
        assert (repo.path / "package.json").read_bytes() == raw.replace(
            b"0.0.0", b"1.0.0"
        )


class TestS6NextVersionAndWhy:
    """S6: the next version and the reason for it."""

    @pytest.mark.smoke
    def test_next(self, repo: RepoBuilder) -> None:
        """--next applies the bump rules to the commits since the tag."""
        repo.tag("v1.2.0")
        repo.commit("fix(core): peel annotated tags (#40)")
        assert repo.run("version", "--next").first == "1.2.1"
        repo.commit("feat(cli): add explain (#41)")
        assert repo.run("version", "--next").first == "1.3.0"
        assert repo.run("version", "--next", "--bump", "major").first == "2.0.0"
        assert (
            repo.run("version", "--next", env={"GITVERSIONED__BUMP": "major"}).first
            == "2.0.0"
        )
        assert (
            repo.run("version", "--next", env={"GITVERSIONED__BUMP": "1.5.0"}).first
            == "1.5.0"
        )

    @pytest.mark.sanity
    def test_explain(self, repo: RepoBuilder) -> None:
        """--explain lists each commit with the level it contributes."""
        repo.tag("v1.2.0")
        repo.commit("chore(deps): bump ruff (#39)")
        repo.commit("feat(cli): add explain (#41)")
        out = repo.run("version", "--next", "--explain").out
        assert "next      1.3.0" in out
        assert "tag v1.2.0" in out
        assert "  minor   feat(cli): add explain (#41)" in out
        assert "  none    chore(deps): bump ruff (#39)" in out
        assert "config    defaults" in out

    @pytest.mark.sanity
    def test_nothing_to_release(self, repo: RepoBuilder) -> None:
        """Maintenance commits alone exit 1."""
        repo.tag("v1.2.0")
        repo.commit("ci: tweak")
        result = repo.run("version", "--next")
        assert result.code == 1
        assert "Nothing to release" in result.err

    @pytest.mark.regression
    def test_pre_release_numbering(self, repo: RepoBuilder) -> None:
        """--pre numbers itself after existing tags."""
        repo.tag("v1.2.0")
        repo.commit("feat: a")
        assert repo.run("version", "--next", "--pre", "rc").first == "1.3.0rc1"
        repo.tag("v1.3.0-rc.1")
        repo.commit("fix: b")
        assert repo.run("version", "--next", "--pre", "rc").first == "1.3.0rc2"
        assert repo.run("version", "--next").first == "1.3.0"


class TestS14MachineReadable:
    """S14: JSON output and exit codes for scripts and agents."""

    @pytest.mark.smoke
    def test_version_json(self, repo: RepoBuilder) -> None:
        """version --json carries both spellings and the facts behind them."""
        repo.tag("v1.2.0")
        sha = repo.commit("feat: a")
        data = repo.run("version", "--json").json
        assert data["pep440"].startswith("1.2.1.dev")
        assert data["semver"].startswith("1.2.1-dev.")
        assert (data["type"], data["tag"], data["distance"], data["sha"]) == (
            "dev",
            "v1.2.0",
            1,
            sha[:7],
        )
        assert data["dirty"] is False

    @pytest.mark.sanity
    def test_errors_are_json_too(self, repo: RepoBuilder) -> None:
        """Failures under --json print a JSON error and keep the exit code."""
        result = repo.run("version", "--bump", "minor", "--json")
        assert result.code == 2
        assert json.loads(result.out)["ok"] is False

    @pytest.mark.sanity
    @pytest.mark.parametrize(
        ("args", "code"),
        [
            (("version", "--type", "weekly"), 2),
            (("version", "not-a-version"), 2),
            (("version", "--dry-run"), 2),
            (("release", "--pr", "--tag"), 2),
        ],
    )
    def test_usage_errors(
        self, repo: RepoBuilder, args: tuple[str, ...], code: int
    ) -> None:
        """Bad usage exits 2."""
        assert repo.run(*args).code == code
