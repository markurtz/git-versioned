"""
Regenerate ``llms-full.txt`` from the project configuration, source and guides.

The file gives a language model the whole project in one read. License headers
are left out to keep it short.

Example:
::
    python scripts/generate_llms_full.py
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Annotated

__all__ = ["OUTPUT", "SECTIONS", "main", "render"]

ROOT: Annotated[Path, "Repository root"] = Path(__file__).resolve().parent.parent
OUTPUT: Annotated[Path, "The generated file"] = ROOT / "llms-full.txt"
SECTIONS: Annotated[
    tuple[tuple[str, tuple[str, ...]], ...],
    "Section titles and the glob patterns of the files each one holds",
] = (
    ("PROJECT CONFIGURATION", ("pyproject.toml",)),
    ("SOURCE", ("src/gitversioned/*.py", "src/gitversioned/plugins/*.py")),
    (
        "DOCUMENTATION",
        (
            "README.md",
            "docs/getting-started/*.md",
            "docs/guides/*.md",
            "examples/*/README.md",
        ),
    ),
)
_LANGUAGES = {".py": "python", ".toml": "toml", ".md": "markdown"}
_HASH_HEADER = re.compile(r"\A(?:#.*\n)+\n?")
_HTML_HEADER = re.compile(r"\A<!--.*?-->\n*", re.DOTALL)


def _body(path: Path) -> str:
    """Read a file without its license header."""
    text = path.read_text(encoding="utf-8")
    if "Licensed under the Apache License" in text[:400]:
        text = (_HTML_HEADER if text.startswith("<!--") else _HASH_HEADER).sub(
            "", text, count=1
        )
    return text.strip("\n")


def render() -> str:
    """
    Build the text of ``llms-full.txt``.

    :return: The whole document.
    """
    parts = [
        "# GitVersioned Full Documentation\n",
        (
            "This file contains the project configuration, the source code and the "
            "guides of gitversioned in one place, to give language models the whole "
            "context. It is generated by `scripts/generate_llms_full.py`.\n"
        ),
    ]
    for number, (title, patterns) in enumerate(SECTIONS, start=1):
        parts.append(f"# SECTION {number}: {title}\n")
        for pattern in patterns:
            for path in sorted(ROOT.glob(pattern)):
                relative = path.relative_to(ROOT).as_posix()
                fence = "````" if path.suffix == ".md" else "```"
                parts.append(
                    f"## File: {relative}\n\n"
                    f"{fence}{_LANGUAGES.get(path.suffix, '')}\n"
                    f"{_body(path)}\n{fence}\n"
                )
    return "\n".join(parts)


def main() -> None:
    """Write ``llms-full.txt``."""
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"[INFO] Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
