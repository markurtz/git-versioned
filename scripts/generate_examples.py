"""
Regenerate the example indexes from ``examples/manifest.toml`` and
``examples/use-cases.toml``.

Writes ``examples/README.md``, ``docs/examples/index.md`` and
``docs/examples/use-cases.md``. With ``--check`` nothing is written, and the
exit code is 1 when a file is out of date.

Example:
::
    python scripts/generate_examples.py
    python scripts/generate_examples.py --check
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Annotated

if sys.version_info >= (3, 11):
    import tomllib
else:  # pragma: no cover
    import tomli as tomllib

__all__ = ["OUTPUTS", "main", "render"]

ROOT: Annotated[Path, "Repository root"] = Path(__file__).resolve().parent.parent
TREE: Annotated[str, "Where examples are browsed on GitHub"] = (
    "https://github.com/markurtz/git-versioned/tree/main/examples"
)
OUTPUTS: Annotated[tuple[str, ...], "The generated files, relative to the root"] = (
    "examples/README.md",
    "docs/examples/index.md",
    "docs/examples/use-cases.md",
)
_LEVELS = ("beginner", "intermediate", "advanced")
_SOURCES = {
    "v03": "Supported by gitversioned 0.3.1",
    "prd": "Added by the 0.4 rewrite",
    "template": "Needed by the markurtz/template generator",
    "competitor": "Offered by other release tools",
}
_NOTE = (
    "<!-- Generated by scripts/generate_examples.py from examples/*.toml; "
    "do not edit. -->"
)


def _load(name: str) -> dict:
    with (ROOT / "examples" / name).open("rb") as handle:
        return tomllib.load(handle)


def _needs(entry: dict) -> str:
    needs = ["git", "Python", *(f"`{tool}`" for tool in entry.get("requires", []))]
    if entry.get("gh"):
        needs.append("`gh` (a stand-in in the tests)")
    return ", ".join(needs)


def _index(examples: dict, link: str) -> list[str]:
    lines: list[str] = []
    for level in _LEVELS:
        topics = [
            (name, entry) for name, entry in examples.items() if entry["level"] == level
        ]
        if not topics:
            continue
        lines += [
            f"### {level.capitalize()}",
            "",
            "| Example | Shows | Needs |",
            "| ------- | ----- | ----- |",
        ]
        lines += [
            f"| [{entry['title']}]({link.format(name=name)}) "
            f"| {entry['summary']} | {_needs(entry)} |"
            for name, entry in topics
        ]
        lines.append("")
    return lines


def _readme(examples: dict, cases: list[dict]) -> str:
    covered = sum(1 for case in cases if case.get("examples"))
    lines = [
        _NOTE,
        "",
        "# Examples",
        "",
        "Every folder here is a small project that uses gitversioned, and its",
        "`README.md` is its test: the console transcripts in it are run, in order, in",
        "a fresh copy of the folder, and must print exactly what they show.",
        "",
        f"{len(examples)} examples cover {covered} of the {len(cases)} use cases in",
        "[`use-cases.toml`](use-cases.toml); the rest are out of scope, each with its",
        "reason. The [use case page](https://markurtz.github.io/git-versioned/examples/use-cases/)",
        "lists them all.",
        "",
        "## Index",
        "",
        *_index(examples, "{name}/README.md"),
        "## Run the tests",
        "",
        "```bash",
        "hatch run project:tests-e2e                  # every example",
        "hatch run project:tests-e2e -k maturin       # one example",
        "python -m pytest examples --update-examples  # rewrite changed output",
        "```",
        "",
        "Examples that need a tool you do not have, such as `cargo`, `npm` or `uv`,",
        "are skipped. [`conftest.py`](conftest.py) describes the transcript format.",
        "",
        "## Add an example",
        "",
        "1. Make a folder with the smallest project that shows one thing, and a",
        "   `README.md` with a `## Run` section of `console` transcripts, a",
        "   `## How it works` section and a `## Next` section.",
        "1. Add an `[example.<folder>]` table to [`manifest.toml`](manifest.toml) and",
        "   name the folder in the use cases it shows in `use-cases.toml`.",
        "1. Run `python -m pytest examples -k <folder> --update-examples` to fill in",
        "   the output, read it, then run `python scripts/generate_examples.py`.",
        "",
    ]
    return "\n".join(lines)


def _docs_index(examples: dict) -> str:
    lines = [
        _NOTE,
        "",
        "# Examples",
        "",
        "Runnable projects live in the",
        f"[`examples/`]({TREE}) folder of the repository. Each one's README is",
        "its test: the commands in it run on every test run, in a fresh copy of the",
        "folder, and must print what the README shows.",
        "",
        "See [Use Cases](use-cases.md) for every use case and the example that",
        "shows it.",
        "",
        "## Example Index",
        "",
        *_index(examples, TREE + "/{name}"),
        "## Try one",
        "",
        "```bash",
        "cp -r examples/hatchling /tmp/hatchling && cd /tmp/hatchling",
        'git init -q && git add -A && git commit -qm "feat: first version"',
        "git tag v1.2.3",
        "gitversioned version",
        "```",
        "",
        "## Run the example tests",
        "",
        "```bash",
        "hatch run project:tests-e2e",
        "```",
        "",
    ]
    return "\n".join(lines)


def _use_cases(cases: list[dict]) -> str:
    lines = [
        _NOTE,
        "",
        "# Use Cases",
        "",
        "Every use case gitversioned is measured against, and the example whose test",
        "shows it working. They come from four places: what 0.3.1 supported, what",
        "the 0.4 rewrite added, what the markurtz/template generator needs, and what",
        "other release tools offer. The source list is",
        f"[`examples/use-cases.toml`]({TREE}/use-cases.toml).",
        "",
    ]
    for source, heading in _SOURCES.items():
        rows = [
            case for case in cases if case["source"] == source and case.get("examples")
        ]
        if not rows:
            continue
        lines += [
            f"## {heading}",
            "",
            "| ID | Use case | Shown in |",
            "| -- | -------- | -------- |",
        ]
        for case in rows:
            shown = ", ".join(f"[{name}]({TREE}/{name})" for name in case["examples"])
            lines.append(f"| {case['id']} | {case['title']} | {shown} |")
        lines.append("")
    out = [case for case in cases if case.get("status") == "out-of-scope"]
    lines += [
        "## Out of Scope",
        "",
        "These are left out on purpose, each for the reason given.",
        "",
        "| ID | Use case | Why |",
        "| -- | -------- | --- |",
    ]
    lines += [f"| {case['id']} | {case['title']} | {case['reason']} |" for case in out]
    lines.append("")
    return "\n".join(lines)


def render() -> dict[str, str]:
    """
    Build every generated file.

    :return: File contents keyed by path relative to the repository root.
    """
    examples = _load("manifest.toml")["example"]
    cases = _load("use-cases.toml")["use-case"]
    return dict(
        zip(
            OUTPUTS,
            (
                _readme(examples, cases),
                _docs_index(examples),
                _use_cases(cases),
            ),
            strict=True,
        )
    )


def main(argv: list[str] | None = None) -> int:
    """Write the files, or with ``--check`` report the stale ones."""
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    stale = []
    for relative, text in render().items():
        path = ROOT / relative
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        if check:
            stale.append(relative)
            continue
        path.write_text(text, encoding="utf-8")
        print(f"[INFO] Wrote {relative}")
    if stale:
        print(
            f"[ERROR] Out of date: {', '.join(stale)}. "
            "Run python scripts/generate_examples.py."
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
